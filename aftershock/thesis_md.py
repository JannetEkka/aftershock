"""Write THESIS.md from results.json. Only sentences that passed the final check are printed."""
import os

from .eventtest import MEASURES, NAMES
from .snapshot import ROOT

HEADS = {"claim": "The claim", "evidence_for": "Evidence for", "evidence_against": "Evidence against",
         "change_our_mind": "What would change our mind"}


def write(r):
    c, t7 = r["counts"], r["tests"]["7"]["summary"]
    L = [f"# Thesis: {r['thesis']['title'] or 'no thesis text survived the checks'}", "",
         f"Generated by `make replay` from the snapshot through {r['snapshot']['cutoff']} "
         f"(fingerprint `{r['snapshot']['fingerprint']}`). Do not edit by hand: every sentence in the four sections below was written by the Judge model from "
         "checked claims only, and stayed only because code found a kept claim behind it and behind every number in it. "
         "The bracketed ids point to those claims in `results.json` and on the page.", "",
         "## The measured finding this thesis rests on", "",
         f"- {c['events']} news events since {r['snapshot']['first_day']}. **{c['moved_price']} moved the price. {c['moved_usage']} moved usage.**",
         f"- The same rule stamps {100 * t7['chance_moved_usage']:.1f}% of ordinary days \"moved usage\"; for the events it is "
         f"{100 * c['moved_usage'] / max(1, t7['events_tested']):.1f}%. For price: {100 * t7['chance_moved_price']:.1f}% of ordinary days, "
         f"{100 * c['moved_price'] / max(1, t7['price_tested']):.1f}% of events.",
         "", "| Measure (7 days after vs 28 before) | Events tested | Moved | Expected by chance (5%) |", "|---|---|---|---|"]
    for m in MEASURES:
        x = r["tests"]["7"]["measures"][m]
        L.append(f"| {NAMES[m]} | {x['tested']} | {x['moved']} | {x['expected_by_chance']} |")
    for key, head in HEADS.items():
        L += ["", f"## {head}", ""]
        kept = [s for s in r["thesis"]["sections"][key] if s["status"] == "kept"]
        L += [f"- {s['text']} [{', '.join(s['claims'])}]" for s in kept] or ["- (No sentence in this section survived the final check.)"]
    if r["thesis"]["note"]:
        L += ["", r["thesis"]["note"]]
    cut = [s for sec in r["thesis"]["sections"].values() for s in sec if s["status"] == "cut"]
    if cut:
        L += ["", "## Sentences the final check cut", ""] + [f"- ~~{s['text']}~~ ({s['reason']})" for s in cut]
    L += ["", "## The claims behind it", "", f"{c['claims_written']} claims written by the Bull and the Bear, {c['claims_kept']} kept, {c['claims_removed']} removed.", "",
          "| Id | Side | Claim | Figure | Recomputed | Result |", "|---|---|---|---|---|---|"]
    for cl in r["claims"]:
        rec = "" if cl["recomputed"] is None else f"{cl['recomputed']:.4g}"
        text = str(cl["text"]).replace("|", "/")
        L.append(f"| {cl['id']} | {cl['side']} | {text} | {cl['figure']} | {rec} | {'kept' if cl['status'] == 'kept' else 'removed: ' + str(cl['reason']).replace('|', '/')} |")
    L += ["", "## Limits", "",
          "- A news spike is a rough stand-in for an influential event, and the news index (GDELT) does not see everything.",
          "- Events can overlap, and 7 days is one choice of window; the README shows 3 and 14 days as well.",
          "- The ordinary-day band is built from the whole history, in which early years swing more than recent ones.",
          "- This is evidence about what followed the news, not about what caused it. It is not investment advice.", ""]
    with open(os.path.join(ROOT, "THESIS.md"), "w") as f:
        f.write("\n".join(L))
